export const PET_SELECT = Object.freeze({
  id: true,
  nickname: true,
  lifeStage: true,
  sizeBand: true,
  weightGrams: true,
  weightUnit: true,
  weightUpdatedAt: true,
  proteinPreferences: true,
  treatPurpose: true,
  treatPurposes: true,
  breedId: true,
  isMixed: true,
  birthdayMonth: true,
  birthdayDay: true,
  birthdaySetAt: true,
  archivedAt: true,
  photo: { select: { updatedAt: true } },
  createdAt: true,
  updatedAt: true,
})

export function mapPet(pet) {
  return {
    id: pet.id,
    nickname: pet.nickname,
    lifeStage: pet.lifeStage ?? null,
    sizeBand: pet.sizeBand ?? null,
    weightGrams: pet.weightGrams ?? null,
    weightUnit: pet.weightUnit ?? null,
    weightUpdatedAt: pet.weightUpdatedAt ? new Date(pet.weightUpdatedAt).toISOString() : null,
    proteinPreferences: [...(pet.proteinPreferences || [])],
    treatPurpose: pet.treatPurpose ?? null,
    treatPurposes: [...(pet.treatPurposes ?? (pet.treatPurpose ? [pet.treatPurpose] : []))],
    breedId: pet.breedId ?? null,
    isMixed: pet.isMixed ?? false,
    birthdayMonth: pet.birthdayMonth ?? null,
    birthdayDay: pet.birthdayDay ?? null,
    birthdaySetAt: pet.birthdaySetAt ? new Date(pet.birthdaySetAt).toISOString() : null,
    archivedAt: pet.archivedAt ? new Date(pet.archivedAt).toISOString() : null,
    hasPhoto: Boolean(pet.photo),
    photoUpdatedAt: pet.photo?.updatedAt ? new Date(pet.photo.updatedAt).toISOString() : null,
    createdAt: pet.createdAt,
    updatedAt: pet.updatedAt,
  }
}
